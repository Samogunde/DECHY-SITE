/**
 * Derives typed graph edges from the `related` blocks on pages and from Work Area ownership, and
 * writes data/relations/derived.yaml. Each relationship is stored once; inverse edges are derived
 * when the graph is read. Edit a page's related block (or a Work Area's primaryService) and rerun:
 *   npx tsx scripts/derive-relations.ts
 * Edges already present in the hand-written files are not duplicated.
 */
import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";
import { buildRegistry } from "../src/lib/content/load";
import type { Relation } from "../src/lib/content/schema";

const registry = buildRegistry();
const TECH_LIKE = new Set([
  "technology",
  "platform",
  "language",
  "framework",
  "provider",
  "tool",
  "integration",
  "ecosystem",
  "concept",
]);

const OUT = path.join(process.cwd(), "data/relations/derived.yaml");
const handWritten = registry.relations.filter(() => true);
// Everything except the previous generated output counts as already present.
const existing = new Set(
  fs
    .readdirSync(path.join(process.cwd(), "data/relations"))
    .filter((f) => f.endsWith(".yaml") && f !== "derived.yaml")
    .flatMap((f) => {
      const parsed = YAML.parse(
        fs.readFileSync(path.join(process.cwd(), "data/relations", f), "utf8"),
      ) as { relations: Relation[] };
      return parsed.relations.map((r) => `${r.from}|${r.type}|${r.to}`);
    }),
);
void handWritten;

const out = new Map<string, Relation>();
const add = (from: string, type: Relation["type"], to: string) => {
  const key = `${from}|${type}|${to}`;
  if (from === to || existing.has(key) || out.has(key)) return;
  out.set(key, { from, type, to });
};

// Every Work Area belongs to its canonical service.
for (const n of registry.nodes.values())
  if (n.type === "work-area" && n.primaryService) add(n.primaryService, "hasWorkArea", n.id);

for (const page of registry.pages) {
  if (!page.entityId) continue;
  const source = registry.nodes.get(page.entityId);
  if (!source) continue;
  for (const b of page.sections) {
    if (b.type !== "related") continue;
    for (const g of b.groups)
      for (const id of g.entityIds) {
        const target = registry.nodes.get(id);
        if (!target) continue;
        const s = source.type;
        const t = target.type;
        // A Solution page lists the services, Work Areas, and technologies it connects to. The
        // edge is stored from that party to the Solution, as the existing pages already do.
        // Industries are never derived for a Solution (Solution to Industry mapping is deferred).
        if (s === "solution") {
          if (t === "service" || t === "work-area" || TECH_LIKE.has(t))
            add(id, "offersSolution", source.id);
          else if (t === "problem") add(source.id, "solves", id);
          continue;
        }
        // An industry page lists the services, Work Areas, and technologies that apply to it.
        // Solutions are linked in the text, never as a relation.
        if (s === "industry") {
          if (t === "service" || t === "work-area" || TECH_LIKE.has(t))
            add(id, "appliesToIndustry", source.id);
          continue;
        }
        if (s === "service" && t === "service") add(source.id, "relatedService", id);
        else if (s === "service" && t === "work-area") add(source.id, "hasWorkArea", id);
        else if (s === "work-area" && t === "service") add(id, "hasWorkArea", source.id);
        else if (s === "work-area" && t === "work-area") add(source.id, "relatedWork", id);
        else if (t === "solution") add(source.id, "offersSolution", id);
        else if (t === "industry") add(source.id, "appliesToIndustry", id);
        else if (t === "problem")
          add(source.id, s === "work-area" ? "solves" : "addressesProblem", id);
        else if (TECH_LIKE.has(s) && t === "service") add(id, "usesTechnology", source.id);
        else if (TECH_LIKE.has(s) && t === "work-area") add(id, "usesTechnology", source.id);
        else if (TECH_LIKE.has(s) && TECH_LIKE.has(t))
          add(source.id, /alternativ/i.test(g.title) ? "alternativeTo" : "integratesWith", id);
        else if (TECH_LIKE.has(t)) add(source.id, "usesTechnology", id);
      }
  }
}

const lines = [
  "# Typed edges derived from page related blocks and Work Area ownership.",
  "# Generated by scripts/derive-relations.ts. Edit a page's related block and rerun; do not edit by hand.",
  "relations:",
  ...[...out.values()].map((r) => `  - { from: ${r.from}, type: ${r.type}, to: ${r.to} }`),
  "",
];
fs.writeFileSync(OUT, lines.join("\n"));
console.log(`derived ${out.size} relations -> data/relations/derived.yaml`);
