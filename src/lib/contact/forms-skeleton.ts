import { NETLIFY_FORMS } from "./netlify-forms";

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

/** The hidden form copies Netlify Forms reads at deploy time (public/__forms.html). */
export function formsSkeleton(): string {
  const forms = Object.values(NETLIFY_FORMS).map((f) => {
    const inputs = [
      `    <input type="hidden" name="form-name" value="${esc(f.name)}" />`,
      `    <input type="hidden" name="subject" value="${esc(f.subject)}" data-remove-prefix />`,
      ...f.fields.map((name) =>
        name === "message" || name === "transcript"
          ? `    <textarea name="${name}"></textarea>`
          : `    <input type="${name === "email" ? "email" : "text"}" name="${esc(name)}" />`,
      ),
    ];
    return `  <form name="${esc(f.name)}" data-netlify="true" hidden>\n${inputs.join("\n")}\n  </form>`;
  });
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="robots" content="noindex, nofollow" />
  <title>Forms | DECHY</title>
</head>
<body>
  <!-- Generated by scripts/build-netlify-forms.ts. Hidden copies of the website forms for Netlify Forms. -->
${forms.join("\n")}
</body>
</html>
`;
}
